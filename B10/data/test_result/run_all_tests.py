"""Re-run every test suite of the case study and save the raw output in data/test_result/.

  Part 2: pytest on Part2/code/mycodo/tests/case_study (83 tests) and the three change demos, then
          delete Part2/code/databases/ (the Flask secret key Mycodo generates on import).
  Part 3: compile and run the 32 test runners (8 patterns x 4 languages) with the same commands
          as Part3/tools/measure.py, then delete the compiled files (java/out/, cpp/*.exe).

Usage (from the team folder):  python -B data/test_result/run_all_tests.py
Needs the venv .venv-mycodo in a parent folder of the team folder (Part 2) and the toolchains listed in
Part3/evidence/toolchains.txt.
"""
import datetime
import glob
import os
import shutil
import subprocess
import sys

TEAM = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(TEAM, 'data', 'test_result')
sys.path.insert(0, os.path.join(TEAM, 'Part3', 'tools'))
from measure import LANGUAGES, PATTERNS, compile_command, find_venv, folder, run_command  # noqa: E402

VENV = find_venv(TEAM)
VENV_PY = os.path.join(VENV, 'Scripts', 'python.exe')

ENV = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')


def portable(text):
    """Logs name no machine paths: the venv becomes <venv> and the team folder B10."""
    for path, name in ((VENV, '<venv>'), (TEAM, 'B10')):
        text = text.replace(path, name).replace(path.replace('\\', '/'), name)
    return text


def run(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, env=ENV)
    rel = os.path.relpath(cwd, TEAM).replace(os.sep, '/')
    shown = ' '.join(os.path.relpath(c, cwd) if os.path.isabs(c) and c.startswith(TEAM) else c for c in cmd)
    return r.returncode, portable(f'$ {shown}   (working folder: {rel})\n{r.stdout}{r.stderr}[exit code: {r.returncode}]\n')


def write(name, text):
    with open(os.path.join(OUT, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# generated by data/test_result/run_all_tests.py on {datetime.datetime.now():%Y-%m-%d %H:%M}\n')
        f.write(text)


def part2():
    code = os.path.join(TEAM, 'Part2', 'code')
    _, log = run([VENV_PY, '-m', 'pytest', '-p', 'no:cacheprovider', '-v', 'mycodo/tests/case_study'], code)
    write('part2_pytest_case_study.txt', log)
    print(log.strip().splitlines()[-2])
    for n in (1, 2, 3):
        d = os.path.join(TEAM, 'Part2', 'changes', f'Change{n}')
        rc, log = run([VENV_PY, 'demo.py'], d)
        write(f'part2_change{n}_demo.txt', log)
        print(f'Change{n} demo exit code {rc}')
    # importing mycodo.config generates databases/flask_secret_key; secrets are not part of the submission
    shutil.rmtree(os.path.join(code, 'databases'), ignore_errors=True)


def part3():
    summary = []
    for key, (fold, name, _) in PATTERNS.items():
        log = []
        for language in LANGUAGES:
            cwd = folder(key, language)
            ok = True
            if compile_command(key, language):
                rc, text = run(compile_command(key, language), cwd)
                log.append(text)
                ok = rc == 0
            if ok:
                rc, text = run(run_command(key, language), cwd)
                log.append(text)
                last = [line for line in text.splitlines() if line.strip()][-2]
            else:
                last = 'COMPILE FAILED'
            summary.append(f'{name:16s} {language:11s} {last}')
            print(summary[-1])
        write(f'part3_tests_{key}.txt', '\n'.join(log))
        shutil.rmtree(os.path.join(TEAM, 'Part3', fold, 'java', 'out'), ignore_errors=True)
        for exe in glob.glob(os.path.join(TEAM, 'Part3', fold, 'cpp', '*.exe')):
            os.remove(exe)
    write('part3_summary.txt', '\n'.join(summary) + '\n')


if __name__ == '__main__':
    part2()
    part3()
