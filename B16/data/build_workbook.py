"""Builds B16_dataset.xlsx: one sheet per CSV dataset plus a Summary sheet whose numbers are
Excel formulas over those sheets. Run from B16/:  python3 data/build_workbook.py
"""
import csv
import re
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

B16 = Path(__file__).resolve().parents[1]
FONT, BOLD = Font(name="Arial", size=10), Font(name="Arial", size=10, bold=True)
HEAD_FILL = PatternFill("solid", fgColor="D9E1F2")
NOTE = Font(name="Arial", size=9, italic=True, color="595959")

SHEETS = [  # sheet name, csv path, source note
    ("patterns", "data/patterns.csv", "Part 1 instances at the baseline (generated by data/build_part1_csv.py)"),
    ("pattern_counts", "data/pattern_counts.csv", "Counts per source version (data/build_part2_csv.py)"),
    ("patterns_evolution", "Part2/pattern_evolution.csv", "One row per instance per version (data/build_part2_csv.py)"),
    ("cross_language", "data/cross_language.csv", "Part 3, measured on my Mac (Part3/measure.py)"),
    ("timing_raw", "Part3/timing-raw.csv", "Part 3 raw times: 1 warm-up + 5 runs per program"),
    ("llm", "data/llm.csv", "Every AI interaction (master file)"),
    ("verification_part1", "Part1/evidence/verification.csv", "Checks of Part 1 LLM claims"),
    ("verification_part2", "Part2/evidence/verification.csv", "Checks of the Part 2 design answer"),
    ("verification_part3", "Part3/llm/verification.csv", "Checks of the Part 3 LLM claims"),
]


def number(value):
    if re.fullmatch(r"-?\d+", value):
        return int(value)
    if re.fullmatch(r"-?\d+\.\d+", value):
        return float(value)
    return value


def add_table(ws, header, rows, note):
    ws.append(header)
    for row in rows:
        ws.append([number(v) for v in row])
    for cell in ws[1]:
        cell.font, cell.fill = BOLD, HEAD_FILL
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.font = FONT
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    for i, col in enumerate(ws.iter_cols(min_row=1, max_row=min(ws.max_row, 60)), start=1):
        longest = max(len(str(c.value or "")) for c in col)
        ws.column_dimensions[get_column_letter(i)].width = max(10, min(60, longest + 2))
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions
    ws.cell(row=ws.max_row + 2, column=1, value=f"Source: {note}").font = NOTE


def read_csv(path):
    with (B16 / path).open(encoding="utf-8") as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def test_counts_rows():
    rows = []
    for line in (B16 / "Part2/changes/launcher_tests_by_snapshot.txt").read_text().splitlines():
        m = re.match(r"(\w+) (.+?) classes (\d+) tests (\d+) skipped (\d+) failures (\d+) errors (\d+)", line)
        suite = ("all jupiter-tests" if "jupiter" in line else "all platform-tests" if "all platform" in line
                 else "launcher tests")
        rows.append([m.group(1), m.group(2), suite, *m.groups()[2:]])
    return ["commit", "snapshot", "suite", "classes", "tests", "skipped", "failures", "errors"], rows


def summary(ws, versions, patterns, languages):
    ws["A1"] = "B16 dataset summary - every number below is a formula over the other sheets"
    ws["A1"].font = Font(name="Arial", size=12, bold=True)
    r = 3
    ws.cell(row=r, column=1, value="Instances per pattern and version (patterns_evolution)").font = BOLD
    r += 1
    ws.cell(row=r, column=1, value="pattern").font = BOLD
    for j, v in enumerate(versions, start=2):
        ws.cell(row=r, column=j, value=v).font = BOLD
        ws.cell(row=r, column=j).alignment = Alignment(wrap_text=True, vertical="top")
    first = r + 1
    for p in patterns:
        r += 1
        ws.cell(row=r, column=1, value=p).font = FONT
        for j in range(2, len(versions) + 2):
            col = get_column_letter(j)
            ws.cell(row=r, column=j, value=f'=COUNTIFS(patterns_evolution!$A:$A,{col}${first - 1},'
                                           f'patterns_evolution!$B:$B,$A{r})').font = FONT
    last = r
    r += 1
    ws.cell(row=r, column=1, value="total instances").font = BOLD
    for j in range(2, len(versions) + 2):
        col = get_column_letter(j)
        ws.cell(row=r, column=j, value=f"=SUM({col}{first}:{col}{last})").font = BOLD
    r += 1
    ws.cell(row=r, column=1, value="pattern types").font = BOLD
    for j in range(2, len(versions) + 2):
        col = get_column_letter(j)
        ws.cell(row=r, column=j, value=f'=COUNTIF({col}{first}:{col}{last},">0")').font = BOLD
    r += 1
    ws.cell(row=r, column=1, value="check: total in pattern_counts").font = NOTE
    for j in range(2, len(versions) + 2):
        col = get_column_letter(j)
        ws.cell(row=r, column=j, value=f'=SUMIFS(pattern_counts!$D:$D,pattern_counts!$A:$A,'
                                       f'{col}${first - 1},pattern_counts!$B:$B,"total_pattern_instances")').font = NOTE

    r += 2
    ws.cell(row=r, column=1, value="Status after change, per version").font = BOLD
    statuses = ["baseline", "preserved", "modified", "extended", "replaced", "removed", "newly_introduced"]
    r += 1
    head = r
    ws.cell(row=r, column=1, value="status").font = BOLD
    for j, v in enumerate(versions, start=2):
        ws.cell(row=r, column=j, value=f"={get_column_letter(j)}{first - 1}").font = BOLD
    for s in statuses:
        r += 1
        ws.cell(row=r, column=1, value=s).font = FONT
        for j in range(2, len(versions) + 2):
            col = get_column_letter(j)
            ws.cell(row=r, column=j, value=f'=COUNTIFS(patterns_evolution!$A:$A,{col}${head},'
                                           f'patterns_evolution!$H:$H,$A{r})').font = FONT

    r += 2
    ws.cell(row=r, column=1, value="Cross-language (cross_language): average over the two patterns").font = BOLD
    r += 1
    for j, h in enumerate(["language", "avg source_loc", "max function CC", "avg median ms", "programs"], start=1):
        ws.cell(row=r, column=j, value=h).font = BOLD
    for lang in languages:
        r += 1
        ws.cell(row=r, column=1, value=lang).font = FONT
        ws.cell(row=r, column=2, value=f"=AVERAGEIF(cross_language!$C:$C,$A{r},cross_language!$E:$E)").font = FONT
        ws.cell(row=r, column=3, value=f"=SUMPRODUCT(MAX((cross_language!$C$2:$C$9=$A{r})*cross_language!$F$2:$F$9))").font = FONT
        ws.cell(row=r, column=4, value=f"=AVERAGEIF(cross_language!$C:$C,$A{r},cross_language!$J:$J)").font = FONT
        ws.cell(row=r, column=5, value=f"=COUNTIF(cross_language!$C:$C,$A{r})").font = FONT
        ws.cell(row=r, column=2).number_format = ws.cell(row=r, column=4).number_format = "0.0"

    r += 2
    ws.cell(row=r, column=1, value="LLM claim verification").font = BOLD
    r += 1
    for j, h in enumerate(["verdict", "Part 1", "Part 2", "Part 3"], start=1):
        ws.cell(row=r, column=j, value=h).font = BOLD
    for v in ["correct", "partially correct", "incorrect*", "cannot confirm"]:
        r += 1
        ws.cell(row=r, column=1, value=v).font = FONT
        for j, sheet in enumerate(["verification_part1", "verification_part2", "verification_part3"], start=2):
            ws.cell(row=r, column=j, value=f'=COUNTIF({sheet}!$E:$E,$A{r})').font = FONT
    r += 1
    ws.cell(row=r, column=1, value="rows checked").font = BOLD
    for j, sheet in enumerate(["verification_part1", "verification_part2", "verification_part3"], start=2):
        ws.cell(row=r, column=j, value=f'=COUNTA({sheet}!$A:$A)-2').font = BOLD
    r += 1
    ws.cell(row=r, column=1, value="rows checked = non-empty column A minus the header and the source note; "
                                   "'incorrect*' also counts 'incorrect (proposed)'").font = NOTE

    r += 2
    ws.cell(row=r, column=1, value="JUnit tests (test_counts)").font = BOLD
    r += 1
    for j, h in enumerate(["measure", "value"], start=1):
        ws.cell(row=r, column=j, value=h).font = BOLD
    n = "test_counts!$C$2:$C$40"
    t = "test_counts!$E$2:$E$40"
    for label, formula in [("launcher tests at baseline", '=SUMPRODUCT((test_counts!$B$2:$B$40="baseline")*test_counts!$E$2:$E$40)'),
                           ("launcher tests after all changes", f'=SUMPRODUCT(MAX(({n}="launcher tests")*{t}))'),
                           ("all platform-tests after all changes", f'=SUMPRODUCT(MAX(({n}="all platform-tests")*{t}))'),
                           ("all jupiter-tests after CH02", f'=SUMPRODUCT(MAX(({n}="all jupiter-tests")*{t}))'),
                           ("failures + errors in all recorded runs", "=SUM(test_counts!$G:$G)+SUM(test_counts!$H:$H)")]:
        r += 1
        ws.cell(row=r, column=1, value=label).font = FONT
        ws.cell(row=r, column=2, value=formula).font = FONT
    ws.column_dimensions["A"].width = 46
    for j in range(2, len(versions) + 2):
        ws.column_dimensions[get_column_letter(j)].width = 24


def main():
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    for name, path, note in SHEETS:
        header, rows = read_csv(path)
        add_table(wb.create_sheet(name), header, rows, note)
    header, rows = test_counts_rows()
    add_table(wb.create_sheet("test_counts"), header, rows,
              "Part2/changes/launcher_tests_by_snapshot.txt (fresh Gradle runs, counted by Part2/evidence/count_tests.py)")
    evo_header, evo = read_csv("Part2/pattern_evolution.csv")
    versions = list(dict.fromkeys(r[0] for r in evo))
    patterns = sorted({r[1] for r in evo})
    languages = list(dict.fromkeys(r[2] for r in read_csv("data/cross_language.csv")[1]))
    summary(ws, versions, patterns, languages)
    wb.calculation.fullCalcOnLoad = True  # no cached values are written; Excel computes on open
    out = B16 / "B16_dataset.xlsx"
    wb.save(out)
    print(f"wrote {out.name}: sheets {wb.sheetnames}")


if __name__ == "__main__":
    main()
